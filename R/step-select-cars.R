#' CARS-Based Feature Selection for Spectral Predictors
#'
#' Applies the Competitive Adaptive Reweighted Sampling (CARS) algorithm to select
#' the minimal optimal set of spectral predictors through iterative PLS regression
#' with exponentially decreasing retention rates and adaptive reweighting.
#'
#' @param recipe A `recipes::recipe()` object.
#' @param ... Selector functions choosing the spectral columns CARS runs on,
#'   e.g. `dplyr::matches("^spec[0-9]+$")` — the names
#'   `step_transform_spectra()` gives its output. Select by name pattern rather
#'   than `all_predictors()`, so that only spectral columns are clustered and
#'   resampled: any other column holding the predictor role when this step
#'   preps would be treated as a wavenumber. A selector matching nothing
#'   aborts at `prep()`.
#' @param outcome Character. Name of the outcome variable to use for model fitting.
#' @param role Character. Role for retained variables. Default is `"predictor"`.
#' @param trained Logical. Required by `recipes`; indicates if the step has been prepped.
#' @param skip Logical. Should this step be skipped during `bake()`? Default is `FALSE`.
#' @param id Character. Unique identifier for the step. Auto-generated by default.
#'
#' @return A `step_select_cars` object that can be added to a recipe.
#'
#' @details
#' This step uses the CARS feature selection algorithm, which iteratively performs
#' PLS regression with Monte Carlo sampling and exponentially decreasing retention
#' rates to identify the minimal optimal wavelength set. The algorithm is run at
#' `prep()` time.
#'
#' For best results, this step should be applied *after* spectral preprocessing (e.g. SNV,
#' derivatives) and *before* PCA or model fitting. CARS is particularly effective for
#' identifying minimal wavelength sets that maintain predictive performance.
#'
#' CARS runs on at most 150 cluster representatives of the selected columns
#' (correlation clustering), after dropping near-constant columns, for 50
#' iterations. Each iteration fits a PLS
#' model of up to five components on a Monte Carlo sample of 80% of the rows,
#' weighted by the bands' accumulated importance, and scores it by its
#' leave-one-out RMSEP at its best number of components; the bands kept then
#' shrink on an exponential schedule to two. The step returns the set of
#' bands the lowest score was measured on (#106), each kept representative
#' bringing its whole cluster. The trained step records this in its `cars`
#' element: the representatives, each iteration's score, the iteration
#' chosen, the bands kept, and `retained_all` (always `FALSE`: CARS always
#' selects).
#'
#' Its refusals (an `outcome` that is not one column of the training data, a
#' `bake()` before `prep()`, new data lacking a column it selected) carry the
#' class `horizons_error_input`. Raised inside `prep()`, recipes wraps them in
#' `recipes_error_step`, so test for the class with `rlang::cnd_inherits()`.
#'
#' @export

## -----------------------------------------------------------------------------
## Step 1: User-facing step constructor
## -----------------------------------------------------------------------------

#' @export
step_select_cars <- function(recipe,
                             ...,
                             outcome,
                             role    = "predictor",
                             trained = FALSE,
                             skip    = FALSE,
                             id      = recipes::rand_id("select_cars")) {

  terms <- rlang::enquos(...)

  recipes::add_step(recipe,
                    step_select_cars_new(terms         = terms,
                                        columns       = NULL,
                                        outcome       = outcome,
                                        role          = role,
                                        trained       = trained,
                                        selected_vars = NULL,
                                        cars          = NULL,
                                        skip          = skip,
                                        id            = id))
}

## -----------------------------------------------------------------------------
## Step 2: Constructor
## -----------------------------------------------------------------------------

## Follows recipes' own contract: `terms` holds the selector quosures and
## survives prep, so a trained recipe can be re-prepped (`fresh = TRUE`);
## `columns` holds the names prep resolved them to, and is what bake reads.
## `cars` is prep's record of what CARS did (see prep()); bake never reads it,
## and a step trained before it existed has none.

#' @keywords internal
#' @noRd
step_select_cars_new <- function(terms,
                                 columns,
                                 outcome,
                                 role,
                                 trained,
                                 selected_vars,
                                 cars = NULL,
                                 skip,
                                 id) {

  out <- list(terms          = terms,
              columns        = columns,
              outcome        = outcome,
              role           = role,
              trained        = trained,
              selected_vars  = selected_vars,
              cars           = cars,
              skip           = skip,
              id             = id )

  class(out) <- c("step_select_cars", "step")
  return(out)

}

## -----------------------------------------------------------------------------
## Step 3: prep() method
## -----------------------------------------------------------------------------

#' @export
prep.step_select_cars <- function(x, training, info = NULL, ...) {

  ## ---------------------------------------------------------------------------
  ## Stage 1: Resolve spectral column names
  ## ---------------------------------------------------------------------------

  selectors <- step_selectors(x, "step_select_cars")
  col_names <- recipes::recipes_eval_select(selectors, training, info)

  check_selection_columns(col_names, "step_select_cars")
  check_step_outcome(x$outcome, training)

  outcome_vec  <- training[[x$outcome]]
  spectra_mat  <- as.matrix(training[, col_names, drop = FALSE])

  ## ---------------------------------------------------------------------------
  ## Stage 2: Cluster predictors before CARS
  ## ---------------------------------------------------------------------------
  ## A near-constant band has no correlation with any other, so it is dropped
  ## before clustering, as step_select_boruta() drops it.

  spectra_mat <- drop_constant_bands(spectra_mat)

  cluster_spectral_predictors(spectra_mat,
                              k      = 150,
                              method = "correlation") -> cluster_result

  reduced_mat   <- cluster_result$reduced_mat
  cluster_map   <- cluster_result$cluster_map
  cluster_vars  <- cluster_result$selected_vars


  ## ---------------------------------------------------------------------------
  ## Stage 3: Run CARS
  ## ---------------------------------------------------------------------------
  ## Each iteration fits a weighted PLS on a Monte Carlo sample of the rows,
  ## using the bands entering it, scores that fit, and eliminates down to a
  ## retention schedule that shrinks exponentially to two bands. The step
  ## returns the set the lowest score was measured on (#106): the set entering
  ## that iteration, kept as the loop runs, not a rerun with new draws.

  n_iterations <- 50
  mc_ratio     <- 0.8
  n_components <- min(5, floor(nrow(reduced_mat) / 3))

  n_samples <- nrow(reduced_mat)
  n_vars    <- ncol(reduced_mat)
  decay     <- exp(log(2 / n_vars) / (n_iterations - 1))

  selected <- seq_len(n_vars)
  weights  <- rep(1, n_vars)
  sets     <- vector("list", n_iterations)
  scores   <- rep(NA_real_, n_iterations)

  for (iter in seq_len(n_iterations)) {

    sets[[iter]] <- selected

    ## The schedule keeps at least two bands, so every set entering an
    ## iteration has two or more
    n_keep     <- min(max(2, floor(n_vars * decay^(iter - 1))), length(selected))
    mc_samples <- sample(n_samples, floor(n_samples * mc_ratio))

    X_weighted <- sweep(reduced_mat[mc_samples, selected, drop = FALSE], 2,
                        weights[selected], "*")
    pls_data   <- as.data.frame(X_weighted)
    pls_data$y <- outcome_vec[mc_samples]

    n_comp  <- min(n_components, ncol(X_weighted) - 1)
    pls_fit <- pls::plsr(y ~ ., data = pls_data, ncomp = n_comp, validation = "LOO")

    ## The cross-validated RMSEP at the best number of components, the
    ## published score (Li et al. 2009); the intercept-only model is left out
    scores[iter] <- min(pls::RMSEP(pls_fit, estimate = "CV", intercept = FALSE)$val)

    ### coef() on a pls fit is a bands x 1 x 1 array.
    importance <- abs(as.vector(stats::coef(pls_fit, ncomp = n_comp)))

    weights[selected] <- weights[selected] * importance
    threshold         <- sort(importance, decreasing = TRUE)[n_keep]
    selected          <- selected[importance >= threshold]

  }

  best <- which.min(scores)

  kept_cluster_vars <- cluster_vars[sets[[best]]]

  ## ---------------------------------------------------------------------------
  ## Stage 4: Map back to original wavenumbers
  ## ---------------------------------------------------------------------------
  ## Each kept representative brings its whole cluster.

  kept_wavenumbers <- unique(unlist(cluster_map[kept_cluster_vars]))

  cars_record <- list(n_representatives = n_vars,
                      scores            = scores,
                      iteration         = best,
                      n_kept            = length(kept_wavenumbers),
                      retained_all      = FALSE)

  ## ---------------------------------------------------------------------------
  ## Stage 5: Return trained step
  ## ---------------------------------------------------------------------------

  step_select_cars_new(terms          = selectors,
                      columns        = col_names,
                      outcome        = x$outcome,
                      role           = x$role,
                      trained        = TRUE,
                      selected_vars  = kept_wavenumbers,
                      cars           = cars_record,
                      skip           = x$skip,
                      id             = x$id)
}


## -----------------------------------------------------------------------------
## Step 4: bake() method
## -----------------------------------------------------------------------------

#' @export
bake.step_select_cars <- function(object, new_data, ...) {

  if (is.null(object$selected_vars)) {
    abort_horizons("This step has not been trained yet. Please call `prep()` first.",
                   kind = "input")
  }

  check_step_new_data(object, new_data)

  ## Retain: selected spectral vars + all non-spectral columns
  keep_cols <- c(object$selected_vars,
                 setdiff(names(new_data),
                         object$columns))

  dplyr::select(new_data, dplyr::all_of(keep_cols))

}

## -----------------------------------------------------------------------------
## Step 5: print() method
## -----------------------------------------------------------------------------

#' @export
print.step_select_cars <- function(x,
                                   width = max(20, options()$width - 30),
                                   ...) {

  cat("CARS-based spectral feature selection step\n")
  cat(glue::glue("\u2022 Outcome column: {x$outcome}\n"))

  if (x$trained) {
    cat(glue::glue("\u2022 {length(x$selected_vars)} wavenumbers retained after CARS\n"))
  } else {
    cat("\u2022 Step not yet trained\n")
  }

  invisible(x)
}


